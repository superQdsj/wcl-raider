"""复盘里需要"认得"的少量职业技能：复活、免死。

只收判断时离不开、而且很少变化的技能。名称一律用 WCL 返回的游戏内名称（run.ab），这里只做分类。
新赛季发现漏掉的 ID，直接加进对应的表；未知 ID 不会报错，只会按"其他"处理。
"""
from __future__ import annotations

from typing import Optional

